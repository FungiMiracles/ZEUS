"""Środowisko: testy odczytu na izolowanej bazie SQLite w pamięci."""
import unittest
from pathlib import Path
from unittest.mock import patch

from flask import Flask, session, template_rendered

from extensions import db
from game.infrastructure_models import InfrastructureProject
from game.communication import messages_bp
from game.event_models import GeneratedEventSnapshot
from game.forum import forum_bp
from game.models import GameUser, GamePlayerCountry
from game.srodowisko import environment_bp
from game.diplomacy import diplomacy_bp
from game.diplomacy_models import DiplomaticAction
from models import Panstwo, Region


class EnvironmentTests(unittest.TestCase):
    def setUp(self):
        root = Path(__file__).resolve().parents[1]
        self.app = Flask(__name__, template_folder=str(root / 'templates'), static_folder=str(root / 'static'))
        self.app.config.update(TESTING=True, SECRET_KEY='environment-test-only', SQLALCHEMY_DATABASE_URI='sqlite:///:memory:')
        db.init_app(self.app)
        from routes_region_secession import region_sovereignty_bp
        self.app.register_blueprint(region_sovereignty_bp)
        self.app.register_blueprint(environment_bp)
        self.app.register_blueprint(diplomacy_bp)
        self.app.register_blueprint(forum_bp)
        self.app.register_blueprint(messages_bp)
        for name in ['wejscie', 'game_main_page', 'game_logout', 'game_demography.page']:
            self.app.add_url_rule('/test/' + name, name, lambda: '')
        self.app.add_template_filter(str, 'spacenum')
        self.app.add_template_filter(str, 'game_money')
        self.ctx = self.app.app_context()
        self.ctx.push()
        db.metadata.create_all(db.engine, tables=[Panstwo.__table__, Region.__table__, GameUser.__table__, GamePlayerCountry.__table__])
        InfrastructureProject.__table__.create(db.engine, checkfirst=True)
        # Points generated by power plants and factories are shown on the environment screen (10 Nov 2026).
        from game.industry_models import PowerPlant
        from game.research_models import AmmunitionFactory
        PowerPlant.__table__.create(db.engine, checkfirst=True)
        AmmunitionFactory.__table__.create(db.engine, checkfirst=True)
        db.session.add_all([
            Panstwo(PANSTWO_ID=1, panstwo_nazwa='Własne państwo'),
            Panstwo(PANSTWO_ID=2, panstwo_nazwa='Obce państwo'),
            *[GameUser(id=i, username=f'Gracz {i}', username_normalized=f'gracz{i}',
                       email=f'{i}@test', email_normalized=f'{i}@test', password_hash='test')
              for i in [1, 2, 3]],
            GamePlayerCountry(user_id=1, panstwo_id=1),
            GamePlayerCountry(user_id=2, panstwo_id=2),
        ])
        db.session.commit()
        self.client = self.app.test_client()
        self.login(1)

    def tearDown(self):
        db.session.remove()
        db.engine.dispose()
        self.ctx.pop()

    def login(self, user_id):
        with self.client.session_transaction() as browser:
            browser['game_user_id'] = user_id

    def render(self):
        contexts = []
        def capture(sender, template, context, **extra):
            contexts.append(context)
        with template_rendered.connected_to(capture, self.app):
            response = self.client.get('/game/srodowisko')
        self.assertEqual(response.status_code, 200)
        return response, contexts[-1]

    def test_averages_missing_values_and_country_isolation(self):
        db.session.add_all([
            Region(region_id=1, panstwo_id=1, region_nazwa='Pierwszy', region_zanieczyszczenie_powietrza=0, region_degradacja_srodowiska=100),
            Region(region_id=2, panstwo_id=1, region_nazwa='Drugi', region_zanieczyszczenie_powietrza=100),
            Region(region_id=3, panstwo_id=1, region_nazwa='Trzeci', region_degradacja_srodowiska=-1),
            Region(region_id=4, panstwo_id=2, region_nazwa='Obcy region', region_zanieczyszczenie_powietrza=40, region_degradacja_srodowiska=0),
        ])
        db.session.commit()
        response, context = self.render()
        metrics = {item['code']: item for item in context['metrics']}
        self.assertEqual(metrics['air']['value'], '50,0')
        self.assertEqual(metrics['air']['known'], 2)
        self.assertEqual(metrics['air']['total'], 3)
        self.assertEqual(metrics['degradation']['value'], '100,0')
        self.assertEqual(metrics['degradation']['known'], 1)
        self.assertIsNone(context['environment_map']['regions']['3']['degradation'])
        self.assertEqual(set(context['environment_map']['regions']), {'1', '2', '3'})
        html = response.get_data(as_text=True)
        self.assertIn('Niepełne dane', html)
        self.assertNotIn('Obcy region', html)
        self.assertIn('role="tablist"', html)
        self.assertIn('aria-current="page"', html)

    def test_no_regions_and_all_missing_or_invalid(self):
        response, context = self.render()
        self.assertTrue(all(item['value'] is None and item['total'] == 0 for item in context['metrics']))
        self.assertIn('Państwo nie ma przypisanych regionów.', response.get_data(as_text=True))
        db.session.add(Region(region_id=1, panstwo_id=1, region_nazwa='Brak danych', region_zanieczyszczenie_powietrza=101))
        db.session.commit()
        response, context = self.render()
        self.assertTrue(all(item['value'] is None and item['known'] == 0 for item in context['metrics']))
        self.assertIsNone(context['environment_map']['regions']['1']['air'])

    def test_access_control(self):
        for user_id in [None, True, '1', 999]:
            self.login(user_id)
            self.assertEqual(self.client.get('/game/srodowisko').status_code, 302)
        self.login(3)
        self.assertEqual(self.client.get('/game/srodowisko').status_code, 403)
        self.login(1)
        db.session.get(GameUser, 1).is_active = False
        db.session.commit()
        self.assertEqual(self.client.get('/game/srodowisko').status_code, 302)
        self.assertEqual(self.client.post('/game/srodowisko').status_code, 405)

    def test_configuration_shared_header_and_read_only(self):
        db.session.add(Region(region_id=1, panstwo_id=1, region_nazwa='<script>region</script>',
                              region_zanieczyszczenie_powietrza=20, region_degradacja_srodowiska=80,
                              region_stan_infra_drogowej=60))
        db.session.commit()
        with patch.object(db.session, 'commit') as commit:
            response, context = self.render()
            commit.assert_not_called()
        self.assertEqual(context['game_country']['infrastruktura'], 60.0)
        self.assertEqual(context['environment_map']['countryId'], 1)
        self.assertEqual(set(context['environment_map']['metrics']), {'air', 'degradation'})
        self.assertIn('entenda_regiony.geojson', context['environment_map']['regionsUrl'])
        self.assertEqual('/wiki/mapa/panstwa.geojson', context['environment_map']['countriesUrl'])
        self.assertIn('&lt;script&gt;region&lt;/script&gt;', response.get_data(as_text=True))


if __name__ == '__main__':
    unittest.main()
